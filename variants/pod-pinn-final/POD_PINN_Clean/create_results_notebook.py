from __future__ import annotations

import base64
import json
from pathlib import Path

import nbformat as nbf


ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "artifacts" / "results"
FIGURES = RESULTS / "figures"
OUT = ROOT / "POD_PINN_Results.ipynb"


def image_output(path: Path):
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return nbf.v4.new_output(
        output_type="display_data",
        data={"image/png": encoded, "text/plain": f"<{path.name}>"},
        metadata={},
    )


def code_cell(source: str, text: str | None = None, image: Path | None = None, count: int = 1):
    outputs = []
    if text is not None:
        outputs.append(nbf.v4.new_output(output_type="stream", name="stdout", text=text))
    if image is not None:
        outputs.append(image_output(image))
    return nbf.v4.new_code_cell(source=source, execution_count=count, outputs=outputs)


summary = json.loads((RESULTS / "results_summary.json").read_text())
rows = summary["architecture_comparison"]
table = "width   u[%]    w[%]    p[%]  nut[%]  mean[%]\n"
for row in rows:
    table += (
        f"{row['width']:>3}  "
        f"{100*row['validation_u_relative_l2']:>6.3f}  "
        f"{100*row['validation_w_relative_l2']:>6.3f}  "
        f"{100*row['validation_p_relative_l2']:>6.3f}  "
        f"{100*row['validation_nut_relative_l2']:>6.3f}  "
        f"{100*row['validation_mean_field_relative_l2']:>7.3f}\n"
    )

operator = summary["operator_validation"]
derivatives = operator["manufactured_relative_rms_derivative_errors"]
residuals = operator["reference_cfd_residual_aggregate"]
operator_text = "Manufactured derivative relative RMS errors:\n"
operator_text += "\n".join(f"  {key}: {value:.3e}" for key, value in derivatives.items())
operator_text += "\n\nMaximum normalized CFD-grid residual imbalance:\n"
for key in ("continuity_normalized", "momentum_x_normalized", "momentum_z_normalized"):
    operator_text += f"  {key}: {residuals[key]['maximum']:.3%}\n"

nb = nbf.v4.new_notebook()
nb["metadata"]["kernelspec"] = {
    "display_name": "Python 3",
    "language": "python",
    "name": "python3",
}
nb["metadata"]["language_info"] = {"name": "python", "version": "3.12"}
nb["cells"] = [
    nbf.v4.new_markdown_cell(
        "# Clean POD–PINN results\n\n"
        "This notebook summarizes the clean rebuild from 48 source CFD arrays. "
        "No old checkpoint or derived model artifact was reused."
    ),
    nbf.v4.new_markdown_cell(
        "## Locked study design\n\n"
        "- Native-mesh, cell-volume-weighted rank-25 POD\n"
        "- Delaunay structured grid only for physics derivatives and visualization\n"
        "- Two hidden layers: 32×32, 64×64, 128×128\n"
        "- tanh, L-BFGS only, L2=1e-4\n"
        "- data/continuity/momentum/boundary multipliers = 1/1/1/1"
    ),
    code_cell(
        "# Precomputed held-out validation summary\nprint(comparison_table)",
        table,
        count=1,
    ),
    code_cell(
        "# Architecture comparison generated by make_results.py\nfrom IPython.display import Image, display\ndisplay(Image('artifacts/results/figures/architecture_comparison.png'))",
        image=FIGURES / "architecture_comparison.png",
        count=2,
    ),
    code_cell(
        "# L-BFGS convergence\ndisplay(Image('artifacts/results/figures/training_convergence.png'))",
        image=FIGURES / "training_convergence.png",
        count=3,
    ),
    nbf.v4.new_markdown_cell("## Delaunay/operator validation"),
    code_cell(
        "# Precomputed manufactured-solution and CFD residual checks\nprint(operator_checks)",
        operator_text,
        count=4,
    ),
    nbf.v4.new_markdown_cell(
        "The analytic derivative check passes comfortably. Reference-CFD residuals "
        "set a finite-difference/interpolation floor, so physics loss should not be "
        "interpreted as exact near-wall PDE enforcement."
    ),
    nbf.v4.new_markdown_cell("## Best model: 64×64"),
    code_cell(
        "# Representative held-out case (V06: Re=4.5e6, AoA=11 deg)\ndisplay(Image('artifacts/results/figures/best_model_heldout_contours.png'))",
        image=FIGURES / "best_model_heldout_contours.png",
        count=5,
    ),
    nbf.v4.new_markdown_cell(
        "## Conclusion\n\n"
        "The 64×64 model gives the lowest mean validation field error (1.426%). "
        "The 128×128 network fits training slightly better but generalizes worse for "
        "cross-flow velocity and pressure. Use `artifacts/models/pod_pinn_2x64_rank25.pt`.\n\n"
        "Limitations: the wall-adjacent 0.02c band is excluded from the structured "
        "physics operator; force metrics are pressure-only; and only 10/48 source "
        "cases pass the conservative force-tail stability flag."
    ),
]
nbf.write(nb, OUT)
print(OUT)
